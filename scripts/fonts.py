#!/usr/bin/env python3
"""Bitmap fonts for the gel alert, from Barlow Condensed (fuelzone/fonts/src,
OFL). The Edge's own fonts are too small for the design's "GEL" and the big
number fonts only have digits.

Writes BMFont (.fnt + .png) and fonts.xml per device into
fuelzone/fonts/<device>/. Sizes are cap heights on the 282 x 470 design,
scaled to the device height. Only the characters the alert draws are
included, to keep memory low.

Needs Pillow: python3 -m venv .venv && .venv/bin/pip install pillow
Run: .venv/bin/python scripts/fonts.py
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent / "fuelzone" / "fonts"
SRC = ROOT / "src"
DESIGN_H = 470
DESIGN_W = 282
# width, height
DEVICES = {"edge1030plus": (282, 470), "edge840": (246, 322)}

DIGITS = "0123456789"
# Smallest cap height on any device, so the small lines stay readable.
MIN_CAP = 10.0
# Scaled by height (it has to fit); the rest by width, which leaves the
# small lines bigger on the relatively wide Edge 840.
BY_HEIGHT = {"AlertBig"}
# id: (ttf, cap height on the design, characters, extra tracking in px)
FONTS = {
    "AlertLabel": ("BarlowCondensed-Bold.ttf", 13.5, "TIMEFORA ", 2.0),
    "AlertBig": ("BarlowCondensed-ExtraBold.ttf", 75.0, "GEL", 0.0),
    "AlertMid": ("BarlowCondensed-ExtraBold.ttf", 20.0, DIGITS + " #,ofg", 0.0),
    "AlertSmall": ("BarlowCondensed-Bold.ttf", 16.0, DIGITS + " Carbsgnow,/h", 0.0),
    # Caps and digits only, so the line height is the cap height and the
    # text centers in the black box.
    "AlertButton": ("BarlowCondensed-ExtraBold.ttf", 21.0, DIGITS + " LOGEDINS", 0.0),
}


def font_for_cap(ttf: Path, cap: float) -> ImageFont.FreeTypeFont:
    """Font size whose "H" is cap px tall."""
    size = cap / 0.7
    for _ in range(4):
        f = ImageFont.truetype(str(ttf), max(1, round(size)))
        l, t, r, b = f.getbbox("H")
        size *= cap / max(1, b - t)
    return ImageFont.truetype(str(ttf), max(1, round(size)))


def build(name: str, ttf: str, cap: float, chars: str, track: float, out: Path) -> None:
    f = font_for_cap(SRC / ttf, cap)
    glyphs = []
    for ch in sorted(set(chars)):
        if ch == " ":
            glyphs.append((ch, None, f.getlength(" ")))
            continue
        bbox = f.getbbox(ch)
        glyphs.append((ch, bbox, f.getlength(ch)))
    top = min(b[1] for _, b, _ in glyphs if b)
    bottom = max(b[3] for _, b, _ in glyphs if b)
    line_h = bottom - top
    tr = round(track * cap / FONTS[name][1]) if track else 0

    # One row atlas, 1 px apart.
    width = sum((b[2] - b[0] + 2) if b else 2 for _, b, _ in glyphs)
    atlas = Image.new("RGBA", (max(width, 1), line_h + 2), (255, 255, 255, 0))
    rows = []
    x = 1
    for ch, b, adv in glyphs:
        if b is None:
            rows.append(f"char id={ord(ch)} x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 "
                        f"xadvance={round(adv) + tr} page=0 chnl=15")
            continue
        w, h = b[2] - b[0], b[3] - b[1]
        # Hard pixels with hinting: the Edge has no alpha blending and turns
        # every partly covered pixel solid, which smears soft edges.
        mask = Image.new("L", (w, h), 0)
        draw = ImageDraw.Draw(mask)
        draw.fontmode = "1"
        draw.text((-b[0], -b[1]), ch, font=f, fill=255)
        glyph = Image.new("RGBA", (w, h), (255, 255, 255, 0))
        glyph.putalpha(mask)
        atlas.paste(glyph, (x, 1))
        rows.append(f"char id={ord(ch)} x={x} y=1 width={w} height={h} xoffset={b[0]} "
                    f"yoffset={b[1] - top} xadvance={round(adv) + tr} page=0 chnl=15")
        x += w + 2

    png = name.lower() + ".png"
    atlas.save(out / png)
    (out / (name.lower() + ".fnt")).write_text("\n".join([
        f'info face="{name}" size={f.size} bold=1 italic=0 charset="" unicode=1 '
        f'stretchH=100 smooth=1 aa=1 padding=0,0,0,0 spacing=1,1',
        f"common lineHeight={line_h} base={line_h} scaleW={atlas.width} "
        f"scaleH={atlas.height} pages=1 packed=0",
        f'page id=0 file="{png}"',
        f"chars count={len(rows)}",
        *rows,
    ]) + "\n")


def main() -> None:
    for dev, (w, h) in DEVICES.items():
        out = ROOT / dev
        out.mkdir(parents=True, exist_ok=True)
        sh = h / DESIGN_H
        sw = min(sh * 1.3, w / DESIGN_W)
        xml = ["<!-- Generated by scripts/fonts.py -->", "<fonts>"]
        for name, (ttf, cap, chars, track) in FONTS.items():
            s = sh if name in BY_HEIGHT else sw
            build(name, ttf, max(cap * s, MIN_CAP), chars, track * s, out)
            xml.append(f'    <font id="{name}" filename="{name.lower()}.fnt" antialias="false"/>')
        xml.append("</fonts>")
        (out / "fonts.xml").write_text("\n".join(xml) + "\n")
        print("wrote", out)


if __name__ == "__main__":
    main()
